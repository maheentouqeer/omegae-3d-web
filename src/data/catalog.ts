// Generate 64 Shelf Slots matching the products across the 8 aisles
export const INITIAL_SHELF_SLOTS: ShelfSlot[] = INITIAL_PRODUCTS.map((prod) => {
  const aisle = AISLE_CONFIG.find((a) => a.number === prod.aisleNumber)!;
  const slotNumInAisle = parseInt(prod.shelfSlotId.split('-')[2], 10) - 1; // 0 to 7
  
  // Arrange in 2 levels: level 0 (lower), level 1 (eye level)
  const shelfLevel = slotNumInAisle % 2 === 0 ? 1 : 0;
  // Position along Z axis from -10 to +2
  const zStep = 1.6;
  const z = -10 + Math.floor(slotNumInAisle / 2) * zStep;
  const x = aisle.x + (slotNumInAisle % 2 === 0 ? 0.35 : -0.35);
  const y = shelfLevel === 1 ? 1.45 : 0.85;

  // Stock variation
  // Make a couple of items low stock for manager alerts
  let currentStock = 14;
  let reorderThreshold = 4;
  if (prod.id === 'food-4') currentStock = 2; // Milk low stock!
  if (prod.id === 'pharm-1') currentStock = 3; // Pain relief low stock!
  if (prod.id === 'drink-2') currentStock = 1; // Cold brew critical!
  if (prod.id === 'elec-2') currentStock = 3; // Earbuds low stock!

  return {
    id: prod.shelfSlotId,
    aisleNumber: prod.aisleNumber,
    shelfLevel,
    positionIndex: slotNumInAisle,
    x,
    y,
    z,
    productId: prod.id,
    maxCapacity: 16,
    currentStock,
    reorderThreshold,
    salesCount: Math.floor(Math.random() * 45) + 12
  };
});
